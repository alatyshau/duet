"""Deploy per-context instruction components into a context's Drive folder.

Triggered by Extension on workspace open (`POST /deploy-instructions`). Reads a
context's `context.json` declarations and materializes them next to the context:

- ``skills`` → ``<context>/.claude/skills/<name>/`` (Claude Code) and
  ``<context>/.agents/skills/<name>/`` (cross-client convention, read by Kimi
  Code). Both targets are Duet-managed: deploy the declared set, prune
  everything else. Absent key → no-op; present (even ``[]``) → manage.
- ``instructions`` → per-client dot-folder files inside the context folder:
  ``.claude/CLAUDE.md`` (Claude Code), ``.kimi-code/AGENTS.md`` (Kimi Code),
  ``.agents/rules/gemini.md`` (Antigravity). Composed from per-client
  templates in this package. Always generated (the templates carry the
  client-specific memory policy even with no user sources). Files are written
  read-only (``0444``); a hand-written file without our banner is silently
  backed up to ``<name>.bak`` before the first overwrite. Legacy root-level
  ``CLAUDE.md``/``AGENTS.md``/``GEMINI.md`` carrying our banner are removed;
  hand-written ones are left untouched.
- ``system_prompt`` → one Claude output-style file as the single source, wired
  into three clients: a bannered copy in ``.claude/output-styles/<name>.md`` +
  ``outputStyle`` in ``.claude/settings.json`` (Claude Code); a
  ``model_instructions_file`` line in ``.codex/config.toml`` pointing at that
  copy (Codex); a rewritten ``.kimi-code/agents/agent.md`` with
  ``override: true`` (Kimi Code). Only Duet's own keys are touched in the two
  shared config files; withdrawal (key absent) removes only what carries our
  banner.

All ``@<name>/<rest>`` declarations are resolved via `at_paths.resolve_at_path`.
"""

from __future__ import annotations

import json
import os
import re
import shutil
import stat
import tempfile
import unicodedata
from dataclasses import dataclass
from pathlib import Path

import yaml

try:
    import tomllib
except ModuleNotFoundError:  # Python 3.10 (Host supports 3.10+): same parser, packaged as `tomli`
    import tomli as tomllib

from .at_paths import resolve_at_path
from .manifest import Manifest

SKILL_MANIFEST = "SKILL.md"
CLAUDE_DIR = ".claude"
AGENTS_DIR = ".agents"
SKILLS_SUBDIR = "skills"
# Holding area inside each skills dir for pruned skills. Never itself pruned
# (it is the backup target). A declared skill may not use this reserved name.
PRUNED_DIR = ".pruned"

# out relative path (inside the context folder) → template filename (in this
# package directory). Per-client dot-folder locations, verified against each
# client's discovery rules:
#   - Claude Code:  `.claude/CLAUDE.md` (official project-instructions location)
#   - Kimi Code:    `.kimi-code/AGENTS.md` (loads without a .git project root —
#                   `.agents/AGENTS.md` is discovered only when `.git` is present)
#   - Antigravity:  `.agents/rules/gemini.md` (workspace rules location)
INSTRUCTION_TEMPLATES = {
    ".claude/CLAUDE.md": "CLAUDE_template.md",
    ".kimi-code/AGENTS.md": "AGENTS_template.md",
    ".agents/rules/gemini.md": "GEMINI_template.md",
}
# Pre-dot-folder layout: instruction files at the context root. Deployed files
# carried our banner and are removed on deploy; hand-written ones stay.
LEGACY_ROOT_INSTRUCTIONS = ("CLAUDE.md", "AGENTS.md", "GEMINI.md")
INSERT_MARKER = "<!-- INSERT USER INSTRUCTIONS -->"
# Substring identifying a Duet-generated instruction file (vs hand-written).
GENERATED_BANNER = "AUTO-GENERATED by Duet"

# Backend package dir. The *_template.md files live in packages/instructions
# (alongside bootstrapper.md, agent cores, index.json) and are bundled next to
# the backend at deploy time (electron-builder + copyPlatformInstructions), so at
# deployed runtime they resolve as siblings of server.py. In dev — when running
# against the source tree — they're found via the sibling packages/instructions
# fallback (see _resolve_template).
_BACKEND_DIR = Path(__file__).resolve().parent.parent
# Sibling platform-instructions dir — dev fallback for the templates.
_INSTRUCTIONS_DIR = _BACKEND_DIR.parent / "instructions"


def deploy_instructions(
    context_folder: Path,
    manifest: Manifest,
    repos_path: Path | None,
    context_folders: dict[str, str],
    backend_dir: Path | None = None,
) -> dict:
    """Deploy all instruction components for one context. Idempotent.

    Returns a report: ``{deployed: {...}, warnings: [...]}``.
    """
    backend_dir = backend_dir or _BACKEND_DIR
    warnings: list[str] = []
    deployed: dict = {}

    deployed.update(
        _deploy_skills(context_folder, manifest.skills, repos_path, context_folders, warnings)
    )
    deployed.update(
        _deploy_instruction_files(
            context_folder, manifest.instructions, repos_path, context_folders, backend_dir, warnings
        )
    )
    deployed.update(
        _deploy_system_prompt(
            context_folder, manifest.system_prompt, repos_path, context_folders, warnings
        )
    )
    return {"deployed": deployed, "warnings": warnings}


