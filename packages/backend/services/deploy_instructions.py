"""Deploy per-context instruction components into a context's Drive folder.

Triggered by Extension on workspace open (`POST /deploy-instructions`). Reads a
context's `context.json` declarations and materializes them next to the context:

- ``skills`` → ``<context>/.claude/skills/<name>/`` (Claude Code) and
  ``<context>/.agents/skills/<name>/`` (cross-client convention, read by Kimi
  Code). Both targets are Duet-managed: deploy the declared set, prune
  everything else. Absent key → no-op; present (even ``[]``) → manage.
- ``instructions`` → per-client dot-folder files inside the context folder:
  ``.claude/CLAUDE.md`` (Claude Code), ``.kimi-code/AGENTS.md`` (Kimi Code),
  ``.agents/rules/gemini.md`` (Antigravity). Composed from per-client
  templates in this package. Always generated (the templates carry the
  client-specific memory policy even with no user sources). Files are written
  read-only (``0444``); a hand-written file without our banner is silently
  backed up to ``<name>.bak`` before the first overwrite. Legacy root-level
  ``CLAUDE.md``/``AGENTS.md``/``GEMINI.md`` carrying our banner are removed;
  hand-written ones are left untouched.

All ``@<name>/<rest>`` declarations are resolved via `at_paths.resolve_at_path`.
"""

from __future__ import annotations

import os
import shutil
import tempfile
import unicodedata
from pathlib import Path

from .at_paths import resolve_at_path
from .manifest import Manifest

SKILL_MANIFEST = "SKILL.md"
CLAUDE_DIR = ".claude"
AGENTS_DIR = ".agents"
SKILLS_SUBDIR = "skills"
# Holding area inside each skills dir for pruned skills. Never itself pruned
# (it is the backup target). A declared skill may not use this reserved name.
PRUNED_DIR = ".pruned"

# out relative path (inside the context folder) → template filename (in this
# package directory). Per-client dot-folder locations, verified against each
# client's discovery rules:
#   - Claude Code:  `.claude/CLAUDE.md` (official project-instructions location)
#   - Kimi Code:    `.kimi-code/AGENTS.md` (loads without a .git project root —
#                   `.agents/AGENTS.md` is discovered only when `.git` is present)
#   - Antigravity:  `.agents/rules/gemini.md` (workspace rules location)
INSTRUCTION_TEMPLATES = {
    ".claude/CLAUDE.md": "CLAUDE_template.md",
    ".kimi-code/AGENTS.md": "AGENTS_template.md",
    ".agents/rules/gemini.md": "GEMINI_template.md",
}
# Pre-dot-folder layout: instruction files at the context root. Deployed files
# carried our banner and are removed on deploy; hand-written ones stay.
LEGACY_ROOT_INSTRUCTIONS = ("CLAUDE.md", "AGENTS.md", "GEMINI.md")
INSERT_MARKER = "<!-- INSERT USER INSTRUCTIONS -->"
# Substring identifying a Duet-generated instruction file (vs hand-written).
GENERATED_BANNER = "AUTO-GENERATED by Duet"

# Backend package dir. The *_template.md files live in packages/instructions
# (alongside bootstrapper.md, agent cores, index.json) and are bundled next to
# the backend at deploy time (electron-builder + copyPlatformInstructions), so at
# deployed runtime they resolve as siblings of server.py. In dev — when running
# against the source tree — they're found via the sibling packages/instructions
# fallback (see _resolve_template).
_BACKEND_DIR = Path(__file__).resolve().parent.parent
# Sibling platform-instructions dir — dev fallback for the templates.
_INSTRUCTIONS_DIR = _BACKEND_DIR.parent / "instructions"


def deploy_instructions(
    context_folder: Path,
    manifest: Manifest,
    repos_path: Path | None,
    context_folders: dict[str, str],
    backend_dir: Path | None = None,
) -> dict:
    """Deploy all instruction components for one context. Idempotent.

    Returns a report: ``{deployed: {...}, warnings: [...]}``.
    """
    backend_dir = backend_dir or _BACKEND_DIR
    warnings: list[str] = []
    deployed: dict = {}

    deployed.update(
        _deploy_skills(context_folder, manifest.skills, repos_path, context_folders, warnings)
    )
    deployed.update(
        _deploy_instruction_files(
            context_folder, manifest.instructions, repos_path, context_folders, backend_dir, warnings
        )
    )
    return {"deployed": deployed, "warnings": warnings}


# =============================================================================
# skills component
# =============================================================================

def _deploy_skills(
    context_folder: Path,
    skills: list[str] | None,
    repos_path: Path | None,
    context_folders: dict[str, str],
    warnings: list[str],
) -> dict:
    # Absent key → don't manage the skills dirs at all.
    if skills is None:
        return {
            "skills_deployed": [],
            "skills_pruned": [],
            "agents_skills_deployed": [],
            "agents_skills_pruned": [],
        }

    to_deploy: list[tuple[str, Path]] = []
    seen: dict[str, str] = {}
    for entry in skills:
        src = resolve_at_path(entry, repos_path, context_folders)
        if src is None:
            warnings.append(f"skills: invalid or unresolvable @-path: {entry}")
            continue
        if not src.is_dir():
            warnings.append(f"skills: not a directory: {entry} ({src})")
            continue
        if not (src / SKILL_MANIFEST).is_file():
            warnings.append(f"skills: missing {SKILL_MANIFEST}: {entry}")
            continue
        name = src.name
        if name == PRUNED_DIR:
            warnings.append(
                f"skills: reserved deploy-name '{PRUNED_DIR}': {entry}; skipping"
            )
            continue
        if name in seen:
            warnings.append(
                f"skills: deploy-name collision '{name}': {entry} would overwrite "
                f"{seen[name]}; skipping"
            )
            continue
        seen[name] = entry
        to_deploy.append((name, src))

    # Two client targets for the same declared set: `.claude/skills/` (Claude
    # Code) and `.agents/skills/` (cross-client convention, read by Kimi Code).
    deployed, pruned = _deploy_and_prune_skills(
        context_folder / CLAUDE_DIR / SKILLS_SUBDIR, to_deploy
    )
    agents_deployed, agents_pruned = _deploy_and_prune_skills(
        context_folder / AGENTS_DIR / SKILLS_SUBDIR, to_deploy
    )

    return {
        "skills_deployed": deployed,
        "skills_pruned": pruned,
        "agents_skills_deployed": agents_deployed,
        "agents_skills_pruned": agents_pruned,
    }


def _deploy_and_prune_skills(
    target_root: Path, to_deploy: list[tuple[str, Path]]
) -> tuple[list[str], list[str]]:
    """Mirror the declared skill set into `target_root`, then prune.

    Prune: any `<target_root>/<x>` not in the declared set is removed, but
    backed up first (symmetric with the instructions `.bak`). Backup = move
    into the `.pruned/` holding area, replacing any earlier backup of the
    same name with the most recent removed state. `.pruned/` is never pruned.
    """
    deployed: list[str] = []
    if to_deploy:
        target_root.mkdir(parents=True, exist_ok=True)
        for name, src in to_deploy:
            _mirror_tree_bytes(src, target_root / name)
            deployed.append(name)

    pruned: list[str] = []
    if target_root.is_dir():
        keep = {name for name, _ in to_deploy}
        for child in sorted(target_root.iterdir()):
            if child.name == PRUNED_DIR:
                continue
            if child.is_dir() and child.name not in keep:
                backup_root = target_root / PRUNED_DIR
                backup_root.mkdir(parents=True, exist_ok=True)
                dst = backup_root / child.name
                if dst.exists():
                    shutil.rmtree(dst, ignore_errors=True)
                shutil.move(str(child), str(dst))
                pruned.append(child.name)

    return deployed, pruned


def _mirror_tree_bytes(src_dir: Path, dst_dir: Path) -> None:
    """Mirror `src_dir` onto `dst_dir` as raw bytes (binary-safe), touching only
    what actually differs.

    Deliberately incremental rather than rmtree-and-rebuild. These trees are
    materialized inside the user's Drive folder, where removing a directory
    means "moved to Drive trash" — and deploy runs on every window open, so an
    unconditional rebuild sent every deployed skill to the trash many times a
    day. Overwriting a file in place is a new Drive revision, not a deletion,
    so only entries the source genuinely dropped are ever unlinked.

    Skill trees are small (hundreds of KB), so the comparison reads whole files
    rather than trusting size+mtime — a git checkout rewrites mtimes on files
    whose content never changed, which would reintroduce the churn.
    """
    # Defense in depth: `_deploy_skills` validates the source, but the prune
    # pass below deletes inside the user's Drive folder. An unreadable or empty
    # source (unmounted repo, revoked permissions) must degrade to a no-op, not
    # to "remove everything".
    if not src_dir.is_dir():
        return
    entries = sorted(src_dir.rglob("*"))
    if not entries:
        return

    dst_dir.mkdir(parents=True, exist_ok=True)

    # Pass 1 — bring the destination up to the source.
    wanted: set[str] = set()
    for src in entries:
        rel = src.relative_to(src_dir)
        wanted.add(_mirror_key(rel))
        out = dst_dir / rel
        if src.is_dir():
            if out.is_symlink() or out.is_file():
                out.unlink()
            out.mkdir(parents=True, exist_ok=True)
        elif src.is_file():
            if out.is_dir() and not out.is_symlink():
                shutil.rmtree(out, ignore_errors=True)
            out.parent.mkdir(parents=True, exist_ok=True)
            _write_if_changed(out, src.read_bytes())

    # Pass 2 — drop what the source no longer has. Deepest paths first, so a
    # directory is emptied before it is removed, over a listing materialized up
    # front because the walk mutates the tree it is walking.
    for stale in sorted(dst_dir.rglob("*"), reverse=True):
        if _mirror_key(stale.relative_to(dst_dir)) in wanted:
            continue
        if stale.is_dir() and not stale.is_symlink():
            shutil.rmtree(stale, ignore_errors=True)
        else:
            stale.unlink(missing_ok=True)


def _mirror_key(rel: Path) -> str:
    """Identity of a relative path for matching the two trees against each other.

    Compared under NFC + casefold because the destination is the user's Drive
    folder: on macOS it is case-insensitive and can hand back names in a
    different Unicode normal form than the source repo stores them in. The
    comparison is deliberately lax — a false match only leaves a stale file
    behind, while a false miss would delete a file we had just written.
    """
    return unicodedata.normalize("NFC", rel.as_posix()).casefold()


def _write_if_changed(target: Path, data: bytes) -> None:
    """Write `data` to `target` only when it differs from what is already there.

    The write goes through a temp file in the same directory plus `os.replace`,
    so a reader never observes a half-written file and a read-only target needs
    no chmod (POSIX rename is governed by the directory). The temp name is
    randomized: a fixed suffix could collide with a real source filename. File
    mode is not carried over from the source — unchanged from the previous
    behaviour, where `write_bytes` also created plain 0644 files.
    """
    try:
        if target.stat().st_size == len(data) and target.read_bytes() == data:
            return
    except OSError:
        pass  # missing or unreadable — fall through and write it

    fd, tmp_name = tempfile.mkstemp(dir=target.parent, prefix=".duet-", suffix=".tmp")
    try:
        with os.fdopen(fd, "wb") as fh:
            fh.write(data)
        os.replace(tmp_name, target)
    except BaseException:
        Path(tmp_name).unlink(missing_ok=True)
        raise


