def _deploy_instruction_files(
    context_folder: Path,
    instructions: list[str] | None,
    repos_path: Path | None,
    context_folders: dict[str, str],
    backend_dir: Path,
    warnings: list[str],
) -> dict:
    # Compose the user body from declared @-path sources (order preserved).
    bodies: list[str] = []
    for entry in instructions or []:
        src = resolve_at_path(entry, repos_path, context_folders)
        if src is None or not src.is_file():
            warnings.append(f"instructions: unresolvable or not a file: {entry}")
            continue
        bodies.append(src.read_text(encoding="utf-8").strip())
    user_body = "\n\n".join(bodies)

    # Always generate all three files — the templates carry the memory policy
    # even when there are no user sources.
    written: list[str] = []
    for out_name, tpl_name in INSTRUCTION_TEMPLATES.items():
        tpl = _resolve_template(backend_dir, tpl_name)
        if tpl is None:
            warnings.append(f"instructions: template missing: {tpl_name}")
            continue
        content = tpl.read_text(encoding="utf-8").replace(INSERT_MARKER, user_body)
        target = context_folder / out_name
        target.parent.mkdir(parents=True, exist_ok=True)
        _write_managed_file(target, content, warnings)
        written.append(out_name)

    removed = _remove_legacy_root_instructions(context_folder, warnings)

    return {"instructions_written": written, "instructions_legacy_removed": removed}


def _remove_legacy_root_instructions(context_folder: Path, warnings: list[str]) -> list[str]:
    """Remove pre-dot-folder root instruction files that carry our banner.

    Hand-written files (no banner) are left untouched. The files are read-only
    (0444), but POSIX unlink needs only a writable directory, so no chmod.
    """
    removed: list[str] = []
    for name in LEGACY_ROOT_INSTRUCTIONS:
        target = context_folder / name
        if not target.is_file():
            continue
        try:
            existing = target.read_text(encoding="utf-8")
        except OSError:
            existing = ""
        if GENERATED_BANNER not in existing:
            continue
        try:
            target.unlink()
            removed.append(name)
        except OSError as e:
            warnings.append(f"instructions: legacy removal failed for {name}: {e}")
    return removed


def _resolve_template(backend_dir: Path, tpl_name: str) -> Path | None:
    """Locate a per-client template.

    At deployed runtime the templates sit next to the backend (bundled from
    packages/instructions). In dev, against the source tree, they live in the
    sibling packages/instructions dir. Returns None if neither exists.
    """
    tpl = backend_dir / tpl_name
    if tpl.is_file():
        return tpl
    tpl = _INSTRUCTIONS_DIR / tpl_name
    return tpl if tpl.is_file() else None


def _write_managed_file(target: Path, content: str, warnings: list[str]) -> None:
    """Write a Duet-managed instruction file read-only (0444).

    If a file already exists WITHOUT our generated banner, it was written by
    hand — silently back it up to ``<name>.bak`` (once) before overwriting.
    """
    if target.exists():
        try:
            existing = target.read_text(encoding="utf-8")
        except OSError:
            existing = ""
        if GENERATED_BANNER not in existing:
            backup = target.with_name(target.name + ".bak")
            if not backup.exists():
                try:
                    backup.write_bytes(target.read_bytes())
                except OSError as e:
                    warnings.append(f"instructions: backup failed for {target.name}: {e}")

    # Write via temp + atomic replace. `os.replace` works over a read-only
    # target on POSIX (directory write permission governs), so no pre-chmod.
    tmp = target.with_name(target.name + ".tmp")
    tmp.write_text(content, encoding="utf-8")
    os.replace(tmp, target)
    os.chmod(target, 0o444)
