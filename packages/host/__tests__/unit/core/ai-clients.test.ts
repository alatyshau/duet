// Thin session prompt written to DuetData/duet.md (output-style + Codex/Antigravity body).
const SESSION_BODY = '# Duet session prompt\ncore-platform-instructions'
const GENERATED_BODY =
  '<!-- AUTO-GENERATED by Duet from @Duet.git/packages/instructions/bootstrapper.md -->\n# Retired prompt'

function writeSessionPrompt(duetDataDir: string, sessionPrompt = SESSION_BODY): void {
  writeFileSync(join(duetDataDir, 'duet.md'), sessionPrompt, 'utf-8')
}

/** Lays out what a backend deploy leaves for the stdio bridge: venv Python + bridge script. */
function deployBridge(duetDataDir: string): void {
  const python = venvPythonPath(join(duetDataDir, '.venv'))
  mkdirSync(join(python, '..'), { recursive: true })
  writeFileSync(python, '')
  mkdirSync(join(duetDataDir, 'backend'), { recursive: true })
  writeFileSync(join(duetDataDir, 'backend', 'mcp_stdio_bridge.py'), '')
}

/**
 * Reconstructs the on-disk frontmatter that ai-clients.ts produces.
 * Mirrors the production helpers — kept in sync via fresh-content tests.
 */
function expectedOutputStyleFrontmatter(): string {
  // Description is wrapped in single quotes in YAML
  return [
    '---',
    'name: duet-core',
    "description: 'Duet platform instructions: workspace orientation, business context, tools, and knowledge persistence.'",
    'keep-coding-instructions: true',
    '---',
    '',
    ''
  ].join('\n')
}

/**
 * Mirrors production `expectedKimiSystemContent` — thin session body followed
 * by the `${base_prompt}` template variable.
 */
function expectedKimiSystemContent(sessionBody: string): string {
  return sessionBody + '\n\n${base_prompt}\n'
}

