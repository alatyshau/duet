  describe('cleanupLegacyClaudeFiles', () => {
    it('removes generated role files but preserves the new style and personal files', () => {
      const retired = [
        join(homeDir, '.claude', 'output-styles', 'duet-executor.md'),
        join(homeDir, '.claude', 'agents', 'duet-executor.md'),
        join(homeDir, '.claude', 'agents', 'duet-vizir.md'),
        join(ctx.duetDataDir, 'duet-executor.md'),
        join(ctx.duetDataDir, 'duet-vizir.md')
      ]
      for (const path of retired) {
        mkdirSync(join(path, '..'), { recursive: true })
        writeFileSync(path, GENERATED_BODY)
      }
      const personal = join(homeDir, '.claude', 'agents', 'vizir.md')
      writeFileSync(personal, '# Personal instructions')
      configureClaudeCode(SESSION_BODY, ctx.duetDataDir, TEST_PORT)
      for (const path of retired) expect(existsSync(path)).toBe(false)
      expect(readFileSync(personal, 'utf-8')).toBe('# Personal instructions')
      expect(readFileSync(join(homeDir, '.claude', 'output-styles', 'duet-core.md'), 'utf-8')).toBe(
        expectedOutputStyleFrontmatter() + SESSION_BODY
      )
      expect(existsSync(join(homeDir, '.claude', 'agents', 'duet.md'))).toBe(false)
      expect(cleanupLegacyClaudeFiles(ctx.duetDataDir)).toEqual({ removed: [], failed: [] })
    })

    it('preserves unmarked files even when their names match retired roles', () => {
      const path = join(homeDir, '.claude', 'agents', 'duet-vizir.md')
      mkdirSync(join(path, '..'), { recursive: true })
      writeFileSync(path, '# User-owned instructions')
      expect(cleanupLegacyClaudeFiles(ctx.duetDataDir)).toEqual({ removed: [], failed: [] })
      expect(readFileSync(path, 'utf-8')).toBe('# User-owned instructions')
    })

    it('does not retire old files or switch styles without a replacement prompt', () => {
      const path = join(homeDir, '.claude', 'output-styles', 'duet-executor.md')
      mkdirSync(join(path, '..'), { recursive: true })
      writeFileSync(path, GENERATED_BODY)
      const settings = join(homeDir, '.claude', 'settings.json')
      writeFileSync(settings, JSON.stringify({ outputStyle: 'duet-executor' }))
      expect(configureClaudeCode(null, ctx.duetDataDir, TEST_PORT).status).toBe('needs_setup')
      expect(readFileSync(path, 'utf-8')).toBe(GENERATED_BODY)
      expect(JSON.parse(readFileSync(settings, 'utf-8')).outputStyle).toBe('duet-executor')
    })

    it('reports unreadable targets without stopping cleanup', () => {
      const broken = join(homeDir, '.claude', 'agents', 'duet-executor.md')
      mkdirSync(broken, { recursive: true })
      const retired = join(ctx.duetDataDir, 'duet-vizir.md')
      writeFileSync(retired, GENERATED_BODY)
      const result = cleanupLegacyClaudeFiles(ctx.duetDataDir)
      expect(result.removed).toEqual([retired])
      expect(result.failed).toHaveLength(1)
      expect(result.failed[0].path).toBe(broken)
    })
  })
